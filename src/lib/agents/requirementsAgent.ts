import { ExtensionComponent, ExtensionSpecification } from '@/types/extension';

export function analyzeRequirements(prompt: string): ExtensionSpecification {
  const lower = prompt.toLowerCase();

  // Target site detection
  const targetSites: string[] = [];
  const hostPermissions: string[] = [];
  let detectedSite = 'any';

  if (lower.includes('youtube') || lower.includes('yt')) {
    detectedSite = 'youtube';
    targetSites.push('https://www.youtube.com/*');
    hostPermissions.push('*://*.youtube.com/*');
  } else if (lower.includes('github')) {
    detectedSite = 'github';
    targetSites.push('https://github.com/*');
    hostPermissions.push('*://*.github.com/*');
  } else if (lower.includes('twitter') || lower.includes('x.com')) {
    detectedSite = 'twitter';
    targetSites.push('https://twitter.com/*', 'https://x.com/*');
    hostPermissions.push('*://*.twitter.com/*', '*://*.x.com/*');
  } else if (lower.includes('reddit')) {
    detectedSite = 'reddit';
    targetSites.push('https://www.reddit.com/*');
    hostPermissions.push('*://*.reddit.com/*');
  } else {
    // Scoped or active tab
    targetSites.push('<all_urls>');
    hostPermissions.push('<all_urls>');
  }

  // Permission extraction
  const permissions: string[] = ['storage']; // almost all extensions require local storage
  if (lower.includes('tab') || lower.includes('session') || lower.includes('window')) {
    permissions.push('tabs');
  }
  if (lower.includes('active') || lower.includes('click') || lower.includes('popup')) {
    if (!permissions.includes('activeTab')) {
      permissions.push('activeTab');
    }
  }
  if (lower.includes('alarm') || lower.includes('timer') || lower.includes('track') || lower.includes('interval')) {
    permissions.push('alarms');
  }

  // Component decision
  const components: ExtensionComponent[] = ['popup', 'content_script'];
  if (lower.includes('background') || lower.includes('tracker') || lower.includes('alarm') || lower.includes('timer')) {
    components.push('service_worker');
  }
  if (lower.includes('options') || lower.includes('settings') || lower.includes('preference')) {
    components.push('options');
  }

  // Feature detection
  const features: string[] = [];
  if (lower.includes('short') || lower.includes('distraction') || lower.includes('hide')) {
    features.push('Distraction-Free UI: Hide Shorts & unwanted feeds');
  }
  if (lower.includes('dark') || lower.includes('theme') || lower.includes('neon') || lower.includes('purple') || lower.includes('black')) {
    features.push('Dark Temptation Aesthetic: Custom neon and dark cyber theme');
  }
  if (lower.includes('time') || lower.includes('track') || lower.includes('viewing')) {
    features.push('Local Session & Watch Time Analytics');
  }
  if (lower.includes('control') || lower.includes('speed') || lower.includes('shortcut')) {
    features.push('Dynamic Playback & Shortcut Enhancements');
  }
  if (features.length === 0) {
    features.push('Dynamic Interface Customizer', 'Local Preference Persistence', 'Instant Toggle Control');
  }

  // Honest Technical Limitations
  const limitations: string[] = [];
  if (detectedSite === 'youtube') {
    limitations.push('Manifest V3 compliance: Interface modifications use MutationObserver and CSS overrides without modifying private player internal binaries.');
    limitations.push('Policy compliance: Does not bypass paid subscriptions, video DRM, or deceptive ad-network evasion.');
  } else {
    limitations.push('Manifest V3 security boundaries: Service workers are ephemeral; all state must persist in chrome.storage.');
  }

  // Name generation
  let name = 'Temptation Browser Utility';
  let description = 'Custom Manifest V3 Chrome extension generated by TEMPTATION AI.';

  if (detectedSite === 'youtube') {
    name = 'YouTube Cyber Focus // Dark Temptation';
    description = 'Distraction-free YouTube experience with neon aesthetic, hidden Shorts, custom video controls, and local watch time telemetry.';
  } else if (lower.includes('dark')) {
    name = 'Obsidian Cyber Theme';
    description = 'High-contrast dark luxury styling with customizable neon accents for modern web interfaces.';
  } else if (lower.includes('summariz')) {
    name = 'Neural Web Summarizer';
    description = 'Instant on-page content extraction, semantic summarization, and key insight synthesis.';
  } else if (lower.includes('tab')) {
    name = 'Apex Tab Commander';
    description = 'High-velocity tab grouping, session persistence, and memory-conscious window manager.';
  }

  return {
    name,
    version: '1.0.0',
    description,
    targetSites,
    permissions,
    hostPermissions,
    components,
    features,
    limitations
  };
}
